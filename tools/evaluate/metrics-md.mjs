//   node tools/evaluate/metrics-md.mjs --check    exits 1 if METRICS.md differs from a fresh generation
//
// Inputs: the implementer's evaluation run (the source of the landing figures) and the auditor's independent run.
// Every figure is copied from a metrics.json/run.json/results.json of those runs, with its numerator and denominator.
// Pure: no clock, no network, no environment.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
