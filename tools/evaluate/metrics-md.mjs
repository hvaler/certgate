// METRICS.md (S4-03): generated from the committed Stage 3 evaluation artifacts, never written by hand.
//
//   node tools/evaluate/metrics-md.mjs            writes METRICS.md
//   node tools/evaluate/metrics-md.mjs --check    exits 1 if METRICS.md differs from a fresh generation
//
// Inputs: the implementer's evaluation run (the source of the landing figures) and the auditor's independent run.
// Every figure is copied from a metrics.json/run.json/results.json of those runs, with its numerator and denominator.
// Pure: no clock, no network, no environment.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
export const METRICS_FILE = path.join(ROOT, "METRICS.md");
export const RUNS = [
  { key: "implementer", label: "Implementer run (source of the landing figures)", dir: "evaluation/runs/real-candidate-dd557fd", results: "results.json" },
  { key: "auditor", label: "Auditor's independent run", dir: "evidence/runs/certgate-001/stage-3/auditor/candidate-3/real-run/eval-retry1", results: "results.json" },
];
const COST_LABEL = "cost reported by the endpoint; Token Factory credits are free and have no monetary value";

function load(run) {
  const read = (f) => JSON.parse(readFileSync(path.join(ROOT, run.dir, f), "utf8"));
  return { ...run, m: read("metrics.json"), r: read("run.json"), res: read(run.results) };
}
const frac = (x) => `${x.numerator} / ${x.denominator}`;
const list = (x) => (x.cases && x.cases.length ? x.cases.join(", ") : "—");
const short = (sha) => String(sha ?? "unknown").slice(0, 8);

export function buildMetricsMd() {
  const runs = RUNS.map(load);
  const L = [];
  const row = (label, f) => L.push(`| ${label} | ${runs.map(f).join(" | ")} |`);
  L.push("# CertGate evaluation metrics");
  L.push("");
  L.push("<!-- GENERATED by `node tools/evaluate/metrics-md.mjs` from the committed Stage 3 evaluation artifacts. Do not edit by hand; `node tools/evaluate/metrics-md.mjs --check` (and `npx vitest run`) fails if this file differs from a fresh generation. -->");
  L.push("");
  L.push("Real model, real endpoint: each run read 27 fictitious certificates (cg-004 … cg-030) through AMD Token Factory. Definitions follow register D3-05 as amended by R3.1 C-08 … C-11 and C-15. cg-001 … cg-003 were used to tune the prompt and are excluded from both runs. The two runs are independent: different seats, different clean checkouts, different times. The landing page shows the figures of the implementer run, and names that run.");
  L.push("");
  L.push("Candidate commits: each run names the commit it actually ran (below). The accepted Stage 3 candidate is `5c904693`. Between these commits the reading path is identical by diff: the reader's request and parsing, the frozen prompt and the rules. The later commits changed receipt contents (the F1 snapshot and the \"as reported by the model\" location label), the UI, the upload policy and the tests.");
  L.push("");
  L.push("## Reporting rules");
  L.push("");
  L.push("- **False conforming** (the grave error): FC-broad = proposal release where the expected proposal is not release, over all cases whose expected proposal is not release. FC-strict = release where the expected proposal is block, over the expected-block cases (C-08). Any false conforming in any real run is a REJECT finding with a root-cause line (C-19).");
  L.push("- **Rule abstention** = proposal review with status processed; **failure** = status error, by class; reported separately, each over all evaluated cases (C-09).");
  L.push("- **Per-field accuracy** compares the model channel with the correct reading of each critical field: correct, unknown, wrong, invented (a value where the field is absent), and **confident-on-illegible** (a confident value where the correct reading is illegible), counted separately (C-10).");
  L.push("- **Seconds and cost per certificate** are over processed cases (status not error), with N; a missing reported cost is unknown, never zero (C-11).");
  L.push("- Requests use **temperature 0** (C-12). The runs are reported side by side, with every per-case proposal difference listed below; a difference is never hidden behind one passing run.");
  L.push("- Receipts and run artifacts carry the endpoint reply's id, created time, model and usage as returned (C-14); GET /usage is read before and after each run and reconciled with the sum of per-reply costs (C-15).");
  L.push("- The tuning cases **cg-001, cg-002 and cg-003** are excluded from the evaluation (D3-03); they are the judge-mode stories.");
  L.push("");
  L.push("## Runs");
  L.push("");
  L.push(`| | ${runs.map((x) => x.label).join(" | ")} |`);
  L.push(`|---|${runs.map(() => "---").join("|")}|`);
  row("Artifacts", (x) => `\`${x.dir}/\``);
  row("Candidate commit", (x) => `\`${short(x.r.candidate_commit)}\``);
  row("Prompt SHA-256", (x) => `\`${short(x.r.prompt_sha256)}…\``);
  row("Started → finished (UTC)", (x) => `${x.r.started_utc} → ${x.r.finished_utc}`);
  row("Endpoint host · model requested", (x) => `${x.r.host} · ${x.r.model_requested}`);
  row("Model as reported", (x) => [...new Set(x.res.map((c) => c.endpoint_response?.model).filter(Boolean))].join(", ") || "unknown");
  row("Outcome", (x) => (x.r.blocked ? `BLOCKED: ${x.r.blocked.reason}` : `completed, ${x.r.completed_cases} of ${x.r.cases.length} cases`));
  L.push("");
  L.push("## Headline");
  L.push("");
  L.push(`| Metric | ${runs.map((x) => x.key).join(" | ")} |`);
  L.push(`|---|${runs.map(() => "---").join("|")}|`);
  row("**False conforming, FC-broad** (released where the expected proposal was not release)", (x) => `**${frac(x.m.headline.fc_broad)}**`);
  row("False conforming, FC-strict (released where the expected proposal was block)", (x) => frac(x.m.headline.fc_strict));
  row("FC-broad over all evaluated cases", (x) => frac(x.m.headline.fc_broad_over_all));
  row("Non-conformities caught (expected block, not released)", (x) => frac(x.m.headline.non_conformities_caught));
  row("… of which proposed block", (x) => frac(x.m.headline.non_conformities_blocked));
  row("Proposal equal to the expected proposal", (x) => frac(x.m.headline.proposal_agreement));
  row("Rule abstention (review, status processed)", (x) => frac(x.m.abstentions.rule_abstention));
  row("Failures (status error)", (x) => frac(x.m.abstentions.failure));
  row("Requests · retries", (x) => `${x.m.retries.requests} · ${x.m.retries.cases_with_retry.length ? x.m.retries.cases_with_retry.join(", ") : "0"}`);
  row("Seconds per certificate (processed; mean · median · N)", (x) => `${x.m.headline.seconds_per_certificate.mean} · ${x.m.headline.seconds_per_certificate.median} · ${x.m.headline.seconds_per_certificate.n}`);
  row("Latency per request, ms (mean · median · N)", (x) => `${x.m.time.latency_ms_per_request.mean} · ${x.m.time.latency_ms_per_request.median} · ${x.m.time.latency_ms_per_request.n}`);
  row("Tokens per certificate (total mean · completion mean · reasoning mean)", (x) => `${x.m.tokens.total_per_certificate.mean} · ${x.m.tokens.completion_per_certificate.mean} · ${x.m.tokens.reasoning_per_certificate.mean}`);
  row(`Cost per certificate (mean · median · N; ${COST_LABEL})`, (x) => `${x.m.headline.cost_per_certificate.mean} · ${x.m.headline.cost_per_certificate.median} · ${x.m.headline.cost_per_certificate.n} (unknown ${x.m.headline.cost_per_certificate.unknown})`);
  L.push("");
  L.push("Cases: non-conformities caught (both runs) — " + runs.map((x) => `${x.key}: ${list(x.m.headline.non_conformities_caught)}`).join("; ") + ". False conforming — " + runs.map((x) => `${x.key}: ${list(x.m.headline.fc_broad)}`).join("; ") + ".");
  L.push("");
  const fcCases = runs.flatMap((x) => x.m.headline.fc_broad.cases.map((c) => `${x.key} ${c}`));
  L.push(fcCases.length === 0 ? "No false conforming in either run, so no root-cause line is owed (C-08)." : `False conforming (root-cause lines owed, C-08): ${fcCases.join(", ")}.`);
  L.push("");
  L.push("## Per-case proposals, both runs (C-12)");
  L.push("");
  L.push(`| Case | Expected | ${runs.map((x) => x.key).join(" | ")} |`);
  L.push(`|---|---|${runs.map(() => "---").join("|")}|`);
  const ids = [...new Set(runs.flatMap((x) => x.res.map((r) => r.case_id)))].sort();
  for (const id of ids) {
    const rs = runs.map((x) => x.res.find((r) => r.case_id === id));
    const exp = rs.find(Boolean)?.expected_proposal ?? "?";
    L.push(`| ${id} | ${exp} | ${rs.map((r) => (r ? (r.proposal === exp ? r.proposal : `**${r.proposal}**`) : "not run")).join(" | ")} |`);
  }
  L.push("");
  const diffs = ids.filter((id) => new Set(runs.map((x) => x.res.find((r) => r.case_id === id)?.proposal)).size > 1);
  L.push(`Cases where the two runs differ: ${diffs.length === 0 ? "none" : diffs.join(", ")}.`);
  L.push("");
  L.push("## Proposal mismatches");
  L.push("");
  for (const x of runs) {
    const mm = x.m.proposal_mismatches;
    L.push(`- ${x.key}: ${mm.length === 0 ? "none" : mm.map((p) => `${p.case_id} proposed ${p.proposal}, expected ${p.expected} (${p.reasons.join(", ")})`).join("; ")}.`);
  }
  L.push("");
  const releases = runs.flatMap((x) => x.m.proposal_mismatches.filter((p) => p.proposal === "release").map((p) => `${x.key} ${p.case_id}`));
  L.push(releases.length === 0 ? "No mismatch in either run is a release." : `Mismatches proposing release: ${releases.join(", ")}.`);
  L.push("");
  L.push("## Per-field accuracy (model channel against the correct reading)");
  L.push("");
  L.push(`| Category | ${runs.map((x) => x.key).join(" | ")} |`);
  L.push(`|---|${runs.map(() => "---").join("|")}|`);
  const FIXED = ["correct", "correct_absent", "correct_unknown", "unknown", "wrong", "invented", "confident_on_illegible"];
  const cats = [...new Set([...FIXED, ...runs.flatMap((x) => Object.keys(x.m.per_field_accuracy.totals))])];
  for (const c of cats) row(c.replace(/_/g, " "), (x) => (x.m.per_field_accuracy.totals[c] ? frac(x.m.per_field_accuracy.totals[c]) : `0 / ${Object.values(x.m.per_field_accuracy.totals)[0]?.denominator ?? "?"}`));
  L.push("");
  L.push("Every wrong field, with its cause as derived from the recorded values:");
  L.push("");
  for (const x of runs) {
    const w = x.m.per_field_accuracy.wrong_causes ?? [];
    const outcome = (f) => {
      const c = x.res.find((r) => r.case_id === f.case_id);
      const ch = c?.reasons?.find((code) => code === `CHANNEL_DISAGREE:${f.field}`);
      return `the case was proposed ${c?.proposal ?? "unknown"}${ch ? ` (${ch}: the model-free text layer disagreed)` : ""}`;
    };
    L.push(`- ${x.key}: ${w.length === 0 ? "none" : w.map((f) => `${f.case_id} \`${f.field}\` read \`${f.model}\`${f.model_unit ? ` ${f.model_unit}` : " with no unit"}, correct \`${f.correct}\`: **${f.cause}**; ${outcome(f)}`).join("; ")}.`);
  }
  L.push("");
  L.push("## Usage reconciliation (GET /usage before and after each run, C-15)");
  L.push("");
  L.push(`| | ${runs.map((x) => x.key).join(" | ")} |`);
  L.push(`|---|${runs.map(() => "---").join("|")}|`);
  row("daily_cost_used before → after", (x) => `${x.m.usage_reconciliation.usage_before_daily_cost_used} → ${x.m.usage_reconciliation.usage_after_daily_cost_used}`);
  row("Delta · sum of per-reply cost · difference", (x) => `${x.m.usage_reconciliation.usage_delta} · ${x.m.usage_reconciliation.sum_of_per_request_cost} · ${x.m.usage_reconciliation.difference}`);
  L.push("");
  L.push(`All costs are the ${COST_LABEL}.`);
  L.push("");
  return L.join("\n") + "\n";
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const fresh = buildMetricsMd();
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(METRICS_FILE, "utf8"); } catch { /* missing */ }
    if (current.replace(/\r\n/g, "\n") !== fresh) { console.error("METRICS.md differs from a fresh generation: run node tools/evaluate/metrics-md.mjs"); process.exit(1); }
    console.log("METRICS.md matches a fresh generation");
  } else {
    writeFileSync(METRICS_FILE, fresh);
    console.log("wrote METRICS.md");
  }
}
